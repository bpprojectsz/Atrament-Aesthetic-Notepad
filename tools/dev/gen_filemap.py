#!/usr/bin/env python3
"""Regenerates the "File map" section of docs/blueprint.md from the real code.

Usage:  python tools/dev/gen_filemap.py          # prints the markdown
        python tools/dev/gen_filemap.py --write  # replaces the section in docs/blueprint.md

For every Dart file under app/lib (generated l10n excluded) it lists the line
count, the first doc comment, the project files it imports ("uses") and the
files that import it ("used by"). Run it after adding, moving or deleting files.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / "app" / "lib"
BEGIN = "<!-- FILEMAP:BEGIN (generated by tools/dev/gen_filemap.py) -->"
END = "<!-- FILEMAP:END -->"


def files():
    return sorted(p for p in LIB.rglob("*.dart") if "/generated/" not in p.as_posix())


def rel(p):
    return p.relative_to(LIB).as_posix()


def resolve(src, imp):
    if imp.startswith("package:atrament/"):
        return LIB / imp[len("package:atrament/"):]
    if imp.startswith("package:") or imp.startswith("dart:"):
        return None
    return (src.parent / imp).resolve()


def summary(text):
    doc = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("///"):
            doc.append(s[3:].strip())
        elif doc:
            break
        elif s and not s.startswith(("import", "export", "//", "library", "part")):
            break
    out = " ".join(d for d in doc if d)
    if out:
        return out[:220]
    names = re.findall(r"^(?:abstract |final |base )?(?:class|enum|mixin|extension)\s+(\w+)", text, re.M)
    return ("Defines " + ", ".join(names[:4])) if names else ""


def build():
    fs = files()
    uses, used_by, info = {}, {p: [] for p in fs}, {}
    for p in fs:
        t = p.read_text(encoding="utf8")
        info[p] = (len(t.splitlines()), summary(t))
        deps = []
        for imp in re.findall(r"^(?:import|export)\s+'([^']+)'", t, re.M):
            r = resolve(p, imp)
            if r and r in used_by and r != p:
                deps.append(r)
        uses[p] = sorted(set(deps))
        for d in uses[p]:
            used_by[d].append(p)
    out = []
    groups = {}
    for p in fs:
        groups.setdefault(rel(p).split("/")[0] if "/" in rel(p) else "(root)", []).append(p)
    for g in sorted(groups):
        out.append(f"### `lib/{g}/`" if g != "(root)" else "### `lib/`")
        out.append("")
        for p in groups[g]:
            n, s = info[p]
            out.append(f"- **`{rel(p)}`** ({n} lines) — {s or '(no doc comment)'}")
            if uses[p]:
                out.append("  - uses: " + ", ".join(f"`{rel(d)}`" for d in uses[p]))
            if used_by[p]:
                ub = sorted(used_by[p])
                shown = ", ".join(f"`{rel(d)}`" for d in ub[:8])
                out.append("  - used by: " + shown + (f" (+{len(ub) - 8} more)" if len(ub) > 8 else ""))
        out.append("")
    return "\n".join(out)


def main():
    md = build()
    if "--write" in sys.argv:
        path = ROOT / "docs" / "blueprint.md"
        text = path.read_text(encoding="utf8")
        a, b = text.index(BEGIN), text.index(END)
        path.write_text(text[: a + len(BEGIN)] + "\n\n" + md + "\n" + text[b:], encoding="utf8")
        print("updated", path)
    else:
        print(md)


if __name__ == "__main__":
    main()
